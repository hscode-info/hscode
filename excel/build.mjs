// Builds functions.js (core.js + glue.js). No dependencies: node build.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const dir = (f) => fileURLToPath(new URL(f, import.meta.url));
export function build() {
	const core = readFileSync(dir('src/core.js'), 'utf8');
	const glue = readFileSync(dir('src/glue.js'), 'utf8');
	return '// Generated by build.mjs from src/core.js and src/glue.js. Do not edit.\n' + core + '\n' + glue;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	writeFileSync(dir('functions.js'), build());
	console.log('wrote functions.js');
}
